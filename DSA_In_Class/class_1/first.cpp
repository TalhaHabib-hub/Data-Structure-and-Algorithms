// Data Structures and Algorithms (DSA)
// DSA is a way of organizing and storing data in memory so that it can be accessed
// and modified efficiently. It helps manage large amounts of data using a structured
// approach for faster processing and better resource usage.

// Primitive data types
// int, float, double, char, bool, void
// A data type is a classification that tells the compiler how to interpret a value.
// Each data type has specific rules for storage, memory usage, and operations.
//
// int: stores whole numbers such as 1, 2, 3
// float: stores decimal numbers such as 1.5, 2.75
// double: stores decimal numbers with higher precision than float
// char: stores a single character such as 'a', 'b', 'c'
// bool: stores true or false values

// Example: int value
// 5 is stored as an integer and the sign bit is 0, which means the number is positive.
// The range of int is from -2,147,483,648 to 2,147,483,647.
// An int uses 32 bits, which is 4 bytes of memory.
// In a 32-bit int, 1 bit is used for the sign and the remaining 31 bits are used for value.

// How 2.5 is stored in memory
// 2.5 is a float value and it is represented using the IEEE 754 floating-point standard.
// A float uses 32 bits divided into:
// 1. sign bit
// 2. exponent
// 3. mantissa (fraction/significand)
// This format allows decimal values to be stored in binary form.

// How 2.40000000000000000000000022 is stored in memory
// This number is a double value, so it is stored using the IEEE 754 double-precision format.
// A double uses 64 bits, which are divided into sign, exponent, and mantissa.
// The value is stored in normalized scientific notation, where the binary point is adjusted
// according to the exponent and the mantissa contains the significant digits.

// Types of Data Structures based on data organization
// 1. Linear Data Structure:
//    Data elements are arranged in a sequence, where each element is connected to the next.
//    Examples: arrays, linked lists, stacks, queues.
//
// 2. Non-Linear Data Structure:
//    Data elements are not arranged in sequence, and there is no direct one-to-one ordering.
//    Examples: trees, graphs.
//
// 3. Hierarchical Data Structure:
//    Data is organized in a tree-like form, where each element has a parent-child relationship.
//    Examples: file systems, organizational charts.

// Types of Data Structures based on data type
// 1. Primitive Data Structure:
//    These are basic built-in data types such as int, float, double, char, and bool.
//
// 2. Non-Primitive Data Structure:
//    These are more complex structures built using primitive types.
//    Examples: arrays, linked lists, stacks, queues, trees, graphs.
//
// 3. Composite Data Structure:
//    A composite structure is formed by combining multiple primitive or non-primitive data types.
//    Examples: structs, classes, records.
//
// 4. Abstract Data Structure:
//    An abstract data structure is defined by its behavior and supported operations,
//    not by its detailed implementation.
//    Examples: stacks, queues, lists, trees.
//
// 5. Dynamic Data Structure:
//    A dynamic data structure can grow or shrink during program execution.
//    Examples: linked lists, trees, graphs.

